const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),{JSDOM}=require("jsdom");
const root=path.resolve(__dirname,"..");
const dom=new JSDOM('<html class="nwp-open"><body><main id="wallet-view"></main><div id="nyan-world-invite"></div></body></html>',{runScripts:"outside-only"});
dom.window.eval(fs.readFileSync(path.join(root,"nyan-world-invite.js"),"utf8"));
assert.equal(dom.window.document.getElementById("nyan-world-invite"),null);
assert.equal(dom.window.document.documentElement.classList.contains("nwp-open"),false);
dom.window.dispatchEvent(new dom.window.Event("nyan-wallet-ready"));
dom.window.document.dispatchEvent(new dom.window.Event("visibilitychange"));
assert.equal(dom.window.document.getElementById("nyan-world-invite"),null);
assert.ok(fs.readFileSync(path.join(root,"nyan-world-info.html"),"utf8").includes("nyan-world-news.html"));
dom.window.close();console.log("OK: popup disabled for cached pages; briefing remains accessible");
